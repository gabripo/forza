// Writes shared/knowledge.json (the built-in lessons, tips and sources), shared/foods.json and shared/energy.mjs
// (the app's calorie targets and meal scores, as plain JavaScript) for Forza! Coach. Run after changing lessons,
// tips, foods or those calculations: `npm run export-knowledge` (CI checks that the files are current).
import { execFileSync } from 'node:child_process'
import { mkdtemp, readFile, rm, writeFile } from 'node:fs/promises'
import { tmpdir } from 'node:os'
import { dirname, join } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const app = join(dirname(fileURLToPath(import.meta.url)), '..')
const dir = await mkdtemp(join(tmpdir(), 'forza-knowledge-'))
const out = join(dir, 'knowledge.mjs')
try {
  execFileSync(join(app, 'node_modules', '.bin', 'rolldown'), ['src/data/knowledge-export.ts', '--format', 'esm', '--file', out], { cwd: app, stdio: 'pipe' })
  const { knowledge, foods } = await import(pathToFileURL(out).href)
  await writeFile(join(app, '..', 'shared', 'knowledge.json'), JSON.stringify(knowledge, null, 1) + '\n')
  await writeFile(join(app, '..', 'shared', 'foods.json'), JSON.stringify(foods) + '\n')
  const energy = join(app, '..', 'shared', 'energy.mjs')
  execFileSync(join(app, 'node_modules', '.bin', 'rolldown'), ['src/data/energy-export.ts', '--format', 'esm', '--file', energy], { cwd: app, stdio: 'pipe' })
  const header = '// Generated by `npm run export-knowledge` in app/ from app/src/lib (calc.ts, energy.ts): do not edit.\n'
  await writeFile(energy, header + (await readFile(energy, 'utf8')))
  console.log(`shared/knowledge.json: ${knowledge.lessons.length} lessons, ${knowledge.tips.length} tips, ${knowledge.sources.length} sources; shared/foods.json: ${foods.length} foods`)
} finally {
  await rm(dir, { recursive: true, force: true })
}
